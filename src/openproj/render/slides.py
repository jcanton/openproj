_SLIDE_SCRIPT = """
<script>
(() => {
const ID = {{ e.id|tojson }};
const MAY_WRITE = {{ editable|tojson }};
const ARTICLE = document.querySelector('.slideedit');
const PROSE = document.getElementById('prose');
const PREVIEW = document.getElementById('preview');
const FITNOTE = document.getElementById('fitnote');
const SAVE = document.getElementById('save');
const RESET = document.getElementById('reset');
const STATE = document.getElementById('state');
const BASE = document.getElementById('base');
// The document as it was when this page was rendered, and the ONE thing Reset
// restores from. Never `defaultValue`: a browser restoring a form on a back
// navigation writes the box and leaves `defaultValue` alone, so Reset would
// have put back something the reader never saw. Same decision, same reason, as
// the record editor's `BASELINE`.
const BASELINE = JSON.stringify(state());
// Ace, where the page was given it. The plain box stays in the DOM and stays
// the thing `state()` reads, exactly as it does on the record page — one place
// knows a textarea has a `.value`, and it is not this file.
const SURFACE = window.aceSurface && MAY_WRITE ? aceSurface(PROSE, PROSE.value) : null;
const text = () => SURFACE ? SURFACE.text() : PROSE.value;

function state() {
  const on = key => {
    const box = ARTICLE.querySelector(`.opt[data-key="${key}"]`);
    return box ? box.checked : true;
  };
  return {
    skip: document.getElementById('skip').checked,
    progress: on('progress'),
    prs: on('prs'),
    lead: on('lead'),
    sections: [...ARTICLE.querySelectorAll('.sec')]
      .filter(box => box.checked).map(box => box.value),
    body: typeof text === 'function' ? text() : PROSE.value,
  };
}

function dirty() { return JSON.stringify(state()) !== BASELINE; }

function said(words) { if (STATE) STATE.textContent = words; }

// --- The preview --------------------------------------------------------
// Asked of the SERVER, and that is the decision worth the round trip. A slide
// is markdown through `_markdown`, sections chosen by `only_sections`, a
// checklist lifted by `checklist_items` and pull requests linked by `_pr_link` —
// five functions in Python, none of which exists in this page. A preview drawn
// here would be a sixth rendering of a slide, written in a second language,
// agreeing with the projector only for as long as somebody kept it in step. The
// deck's whole argument is against exactly that.
let asked = null;
let waiting = false;
const PREVIEW_MS = 400;

async function draw() {
  waiting = false;
  const sending = JSON.stringify(state());
  const answer = await fetch('/api/slide/preview', {
    method: 'POST',
    headers: {'content-type': 'application/json'},
    body: JSON.stringify({record_id: ID, slide: state()}),
  });
  if (!answer.ok) {
    // The preview failing is not the save failing, and it must not read as
    // though it were: the text in the box is untouched and still saveable.
    FITNOTE.textContent = 'The preview could not be drawn just now.';
    return;
  }
  const drawn = await answer.json();
  PREVIEW.innerHTML = drawn.html;
  fit();
}

function refresh() {
  if (waiting) clearTimeout(asked);
  waiting = true;
  asked = setTimeout(draw, PREVIEW_MS);
}

// Does it fit? Asked of the browser, after the drawing, because whether 300
// words fit in 720px depends on the font and the wrapping and only the thing
// doing the layout knows both. This is the pane's real job: the canvas is fixed
// and clipped, so without this mark an author would be told nothing at all
// about the paragraph the room is never going to see.
function fit() {
  const room = PREVIEW.clientWidth;
  if (room > 0) PREVIEW.style.setProperty('--fit', String(room / 1280));
  const over = [...PREVIEW.querySelectorAll('.slide')]
    .filter(slide => slide.scrollHeight > slide.clientHeight + 1);
  for (const slide of PREVIEW.querySelectorAll('.slide'))
    slide.classList.toggle('spills', over.includes(slide));
  FITNOTE.textContent = over.length
    ? `${over.length} of these slides ${over.length === 1 ? 'holds' : 'hold'} more than fits. `
      + 'Take something out, or split it with \\\\newslide.'
    : '';
}

// --- Saving -------------------------------------------------------------
async function save() {
  if (!MAY_WRITE) return;
  SAVE.disabled = true;
  said('Saving…');
  try {
    const answer = await fetch('/api/record/' + encodeURIComponent(ID), {
      method: 'PATCH',
      headers: {'content-type': 'application/json'},
      // `body: null` and not the record's body: this editor does not have the
      // record's document on screen and must not write one. A save that carried
      // an empty body would erase the shaping document from a page that never
      // showed it.
      body: JSON.stringify({base_commit: BASE.value, fields: {slide: state()}, body: null}),
    });
    const result = await answer.json().catch(() => ({}));
    if (!answer.ok) {
      // The message the server wrote, because it names the field and why. A
      // generic "could not save" here would throw away the one sentence that
      // says what to do about it.
      said(result.detail || 'That could not be saved.');
      return;
    }
    if (result.commit) BASE.value = result.commit;
    said('Saved.');
  } finally {
    SAVE.disabled = false;
  }
}

if (MAY_WRITE) {
  SAVE.addEventListener('click', save);
  RESET.addEventListener('click', () => {
    const was = JSON.parse(BASELINE);
    document.getElementById('skip').checked = was.skip;
    for (const box of ARTICLE.querySelectorAll('.opt'))
      box.checked = was[box.dataset.key];
    for (const box of ARTICLE.querySelectorAll('.sec'))
      box.checked = was.sections.includes(box.value);
    // `splice` and never `setValue`: it is the surface's only write, and
    // `test_the_second_surface_never_sets_or_replaces_the_whole_document` holds
    // it to that by reading the shipped page. Whole-document boundaries, so the
    // UTF-16 index space `positionToIndex` uses cannot cut a surrogate pair —
    // the defect that shipped once already and rewrote somebody's emoji.
    if (SURFACE) SURFACE.splice(0, text().length, was.body);
    else PROSE.value = was.body;
    said('Reset.');
    refresh();
  });
  // Nothing autosaves here, so leaving with unsaved work has to be said. One
  // model per page and it is visible: the bar carries the state and this is the
  // last thing it can say.
  addEventListener('beforeunload', event => {
    if (dirty()) event.preventDefault();
  });
}

ARTICLE.addEventListener('change', refresh);
if (SURFACE) SURFACE.onInput(refresh); else PROSE.addEventListener('input', refresh);
addEventListener('resize', fit);
document.fonts?.ready.then(fit);
fit();
})();
</script>
"""


def render_slide_editor(
    index: Index,
    record_id: str,
    links: Links = ROUTES,
    base_commit: str | None = None,
    may_write: bool = False,
    editor: str = "ace",
    asset: Callable[[str], bytes | None] | None = None,
) -> str:
    """One record's slide, as three panes on the record's own address.

    `base_commit` and `may_write` decide whether this is an editor or a reading
    of one, the same way they do on the record page and for the same reason: a
    reader offered a Save is offered a 403 dressed as a control, and the three
    panes are worth reading either way — the middle one simply becomes the list
    of what this slide is made of.
    """
    record = index.records[record_id]
    editable = bool(base_commit and may_write)
    slide = record.slide if record.slide is not None else _seeded(record)
    assets = _inlined_assets([record.body, slide.body], asset) if asset else {}
    view = {
        "id": record.id,
        "title": record.title,
        "cycle": record.cycle,
        # A pitch with tasks under it is a rollup and `_deck_view` gives it no
        # slide — its progress IS its tasks and its people are their people, so
        # a slide of its own would put the same work on the screen twice. Read
        # from the index rather than restated, so this and the deck cannot come
        # to different conclusions about what a leaf is.
        "rollup": bool(index.children.get(record.id)),
        # Which slide of the deck this is, so the line above is a place and not
        # only a link. `None` where the record is on no deck at all, which the
        # branch above has already taken.
        "at": _place(index, record),
        "rows": _fact_rows(index, record, links),
        "progress": _progress_view(index, record),
        "body": _body_html(record, links),
        "slide": slide,
        "boxes": _boxes(record),
        # Whether there is any opening text to offer a box for. A checkbox
        # governing something the record does not have is a control whose only
        # honest state is off, and a row of those is how a form stops being read.
        "lead_exists": bool(lead_text(_said(record))),
        "preview": slide_html(index, record, links, assets),
    }
    # `_fragment` and not `_compiled(...).render(...)`, which is what this was
    # and which silently escaped the whole page. `render` answers a `str`, so
    # `str + Markup` reaches `Markup.__radd__`, which escapes the left side: the
    # body arrived at `_page` as `&lt;article class=&#34;slideedit&#34;…`, a
    # complete and completely inert copy of the editor. `_fragment` types the
    # piece as the markup it is, which is the whole reason it exists — its own
    # docstring says so.
    ace = _ace_wanted(editor, base_commit, may_write)
    return _page(
        f"openproj — {record.title}: the slide",
        _fragment(
            _SLIDE + _SLIDE_SCRIPT,
            e=view,
            links=links,
            editable=editable,
            base_commit=base_commit or "",
        )
        + (_ace() if ace else Markup(""))
        + (_ACE_SURFACE if ace else Markup("")),
        _DETAIL_STYLE + _DECK_STYLE + _SLIDE_STYLE,
        links,
        "records",
        index.unreadable,
    )
