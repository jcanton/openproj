def _boxes(record: Record) -> list[dict]:
    """The section checkboxes, reconciled with the record as it is right now.

    **The reconciliation is here and it writes nothing.** jcanton asked for a
    "bottommatter which is autogenerated when opening the slide editing page",
    and this is that, minus the write: a GET that commits would fire on every
    visit, including every visit by somebody the write path would refuse, so
    opening the page would be a 403 for a reader and a commit for everybody
    else. Computing it on open and storing it on Save is the same outcome with
    neither.

    A section the record has grown since the slide was last saved is offered
    unticked — jcanton, 2026-08-25: "newly-discovered section should always
    arrive but not checked, default is leave out". A record that has never been
    personalised is seeded from `_seeded` instead, so its boxes describe the
    slide the deck is drawing for it today and pressing Save without touching
    anything changes nothing. Without that carve-out the first Save on every
    record in the plan would have blanked its slide.

    A name stored by a section that has since been DELETED is not offered, and
    is not lost either: it stays in the file, `only_sections` matches nothing for
    it, and it starts drawing again if the heading comes back. Dropping it here
    would turn a rename-and-rename-back into a silent deletion.
    """
    stored = record.slide if record.slide is not None else _seeded(record)
    chosen = set(stored.sections)
    fresh = record.slide is None
    return [
        {
            "name": name,
            "label": _human(name),
            "on": name in chosen,
            # What the box would have been, so the editor can mark what has
            # arrived since the last save. A person who opens a slide they
            # personalised in July wants to see WHICH heading is new, not to
            # diff two lists in their head.
            "new": not fresh and name not in chosen,
            "bet": is_bet,
        }
        for name, is_bet in choosable(record)
    ]


def _place(index: Index, record: Record) -> int | None:
    """Which slide of its cycle's deck this record's first slide is, counting the
    title slide as one.

    Asked of `_deck_view` itself rather than counted here, so the number on this
    page and the number under the presenter's thumb are the same number. A second
    count would agree with the deck until the day somebody changed the ordering
    or the leaf rule, and then it would be a page confidently naming the wrong
    slide — which is worse than naming none.
    """
    if record.cycle is None:
        return None
    drawn = _deck_view(index, record.cycle, ROUTES)["slides"]
    for at, one in enumerate(drawn):
        if one["id"] == record.id:
            # Plus two: `enumerate` is zero-based and the title slide is drawn
            # by the template rather than by `slides`, so it is in neither.
            return at + 2
    return None


